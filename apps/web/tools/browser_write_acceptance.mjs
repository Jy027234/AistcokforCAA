import { writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { launchIndependentChrome } from "./independent_chrome.mjs";

const args = process.argv.slice(2);
const flag = (name, fallback) => args.includes(`--${name}`) ? args[args.indexOf(`--${name}`) + 1] : fallback;
const url = flag("url", "http://127.0.0.1:8877");
const output = resolve(flag("out", "../../tmp/frontend-browser-acceptance-20261013/write-flow"));
const state = async () => { const response = await fetch(`${url}/__acceptance__/state`); if (!response.ok) throw new Error("Missing isolated fixture"); return response.json(); };
const initial = await state();
if (!initial.label.includes("隔离本地验收") || initial.counts.research_simulation_draft || initial.counts.decision_log) throw new Error("Write acceptance requires a fresh marked fixture, never an existing user ledger");
const report = { mode: "real-browser-real-isolated-api", url, fixture: initial, checks: [], screenshots: [] };
const chrome = await launchIndependentChrome(output);
const check = (name, ok, detail) => { report.checks.push({ name, ok: Boolean(ok), detail }); if (!ok) throw new Error(name); console.log(`PASS ${name}`); };
const shot = async name => report.screenshots.push({ name, path: await chrome.screenshot(name) });
const visibleText = text => `document.body.innerText.includes(${JSON.stringify(text)})`;
const buttonEnabled = text => `Array.from(document.querySelectorAll('button')).some(el=>el.checkVisibility()&&!el.disabled&&el.textContent.trim()===${JSON.stringify(text)})`;
try {
  await chrome.viewport(1440, 1000);
  await chrome.send("Page.navigate", { url: `${url}/#research` });
  await chrome.waitFor(buttonEnabled("检查模拟资格"), "research card loaded");
  await chrome.fill("#research-candidates-search", "合成");
  await chrome.waitFor("!document.body.innerText.includes('正在读取研究候选名单')", "search completed");
  await chrome.click(".research-grid > .card:first-child li:nth-child(1) .btn-sm", "加入比较");
  await chrome.click(".research-grid > .card:first-child li:nth-child(2) .btn-sm", "加入比较");
  check("two-candidate-comparison", await chrome.waitFor(visibleText("移出比较"), "comparison"));
  await shot("01-desktop-research-compare");
  await chrome.click("button", "检查模拟资格");
  await chrome.waitFor("location.hash === '#portfolio' && !!document.querySelector('input[aria-label=\"选择 合成示例·银行（隔离验收）\"]')?.checked", "same-source checked selection");
  check("research-selection-handoff", true);
  await chrome.fill('input[placeholder="记录本次选择依据"]', "隔离浏览器验收：核验原资料后选择，保留这个原理由");
  await chrome.click("button", "生成并保存模拟草稿（1 只）");
  await chrome.waitFor(visibleText("等待执行日行情"), "saved waiting choice");
  const waiting = await state();
  check("waiting-draft-does-not-trade", waiting.counts.research_simulation_draft === 1 && waiting.counts.simulation_plan === 0 && waiting.counts.fill === 0);
  await shot("02-desktop-saved-waiting");
  const published = await fetch(`${url}/__acceptance__/publish-execution`, { method: "POST", headers: { "X-Aquant-Subject": "user:demo" } });
  check("fixture-execution-published", published.ok);
  await chrome.click("button", "刷新资格与草稿");
  await chrome.waitFor(buttonEnabled("检查 2026-09-14 模拟预览"), "execution available");
  await chrome.click("button", "检查 2026-09-14 模拟预览");
  await chrome.waitFor(buttonEnabled("确认并冻结此模拟计划"), "reviewed choice");
  await chrome.click('nav[aria-label="主要任务"] button', "研究");
  check("research-filter-retained", await chrome.evaluate("document.querySelector('#research-candidates-search').value === '合成'"));
  await chrome.click('nav[aria-label="主要任务"] button', "模拟组合");
  await chrome.waitFor(buttonEnabled("确认并冻结此模拟计划"), "review preserved after navigation");
  check("review-kept-on-navigation", true);
  await shot("03-desktop-reviewed-choice");
  await chrome.click("button", "确认并冻结此模拟计划");
  await chrome.waitFor(buttonEnabled("执行本交易日"), "frozen plan execution entry");
  const frozen = await state();
  check("explicit-confirmation-before-execution", frozen.counts.simulation_plan === 1 && frozen.counts.decision_log === 1 && frozen.counts.fill === 0);
  await shot("04-desktop-frozen-plan");
  await chrome.click("button", "执行本交易日");
  await chrome.waitFor(visibleText("本交易日已执行"), "executed plan");
  await chrome.click("button", "计算日终净值");
  await chrome.waitFor(visibleText("已发布"), "published valuation");
  await chrome.click("button", "逐项对账");
  await chrome.waitFor(visibleText("账本逐项一致"), "reconciled ledger");
  const executed = await state();
  check("actual-isolated-fill-and-valuation", executed.counts.fill === 1 && executed.counts.valuation === 1);
  await shot("05-desktop-valued-reconciled");
  await chrome.viewport(390, 844, true);
  await chrome.send("Page.reload");
  await chrome.waitFor(visibleText("本交易日已执行"), "mobile reload durable plan");
  check("mobile-refresh-restores-executed-plan", true);
  await chrome.click("button", "查看账本明细");
  await chrome.waitFor(visibleText("账本明细"), "mobile ledger");
  await shot("06-mobile-executed-ledger");
  await chrome.click("button", "维持当前组合");
  await chrome.fill("textarea", "隔离浏览器验收：保持已有模拟持仓，继续观察原判断");
  await chrome.click("button", "保存维持决定");
  await chrome.waitFor(visibleText("维持决定已保存"), "keep decision saved");
  const kept = await state();
  check("keep-record-does-not-change-ledger", kept.counts.decision_log === 2 && ["order", "fill", "cash_entry", "valuation", "simulation_plan"].every(table => kept.counts[table] === executed.counts[table]));
  await shot("07-mobile-keep-decision");
  await chrome.click("button", "回看这次判断");
  await chrome.waitFor(visibleText("隔离浏览器验收：保持已有模拟持仓"), "original keep reason in review");
  check("mobile-review-reads-original-reason", true);
  await chrome.evaluate("[...document.querySelectorAll('.decision-journey-step p')].find(el=>el.textContent.startsWith('隔离浏览器验收：保持已有模拟持仓'))?.scrollIntoView({block:'center'})");
  await shot("08-mobile-review-original");
  const overflow = await chrome.evaluate("document.documentElement.scrollWidth > 391 || innerWidth > 391");
  check("mobile-written-state-no-document-overflow", !overflow);
  await chrome.click(".utility-menu > summary");
  const menu = await chrome.evaluate("(() => {const r=document.querySelector('.utility-menu-items').getBoundingClientRect();return {left:r.left,right:r.right,width:innerWidth}})()");
  check("mobile-utility-menu-contained", menu.left >= 0 && menu.right <= menu.width);
  await shot("09-mobile-utility-menu");
  await chrome.click(".utility-menu button", "每日更新设置");
  await chrome.waitFor("location.hash === '#settings'", "mobile settings tap");
  check("mobile-settings-touch-navigation", true);
  check("utility-menu-closes-after-navigation", await chrome.evaluate("!document.querySelector('.utility-menu').open"));
  const exceptions = chrome.events.filter(item => item.method === "Runtime.exceptionThrown");
  check("no-browser-runtime-exceptions", exceptions.length === 0);
  report.finalState = await state();
} catch (error) {
  report.error = error.message; console.error(error.message); process.exitCode = 1;
  report.pageText = await chrome.evaluate("document.body.innerText.slice(0,9000)").catch(() => "unavailable");
  await shot("failure-state").catch(() => {});
} finally {
  report.networkWrites = chrome.events.filter(item => item.method === "Network.requestWillBeSent" && item.params.request.method === "POST").map(item => item.params.request.url);
  writeFileSync(join(output, "write-report.json"), JSON.stringify(report, null, 2));
  await chrome.close();
}
